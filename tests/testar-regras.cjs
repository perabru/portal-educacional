// Execute com Firebase Database Emulator. Nenhum teste usa o banco de produção.
const {readFileSync}=require('node:fs');
const {resolve}=require('node:path');
const {initializeTestEnvironment,assertSucceeds,assertFails}=require('@firebase/rules-unit-testing');
const {ref,get,set,update}=require('firebase/database');
const root='portalEducacionalV1',projectId='demo-portal-educacional';
const studentId='student_123',otherId='student_456';
const profile={nome:'Aluno Teste',email:'aluno@example.com',ano:'1º ano',turma:'1IA',materias:{bd:true},instituicao:'UNIVAP',status:'pendente',criadoEm:1,atualizadoEm:1};
const submission={disciplina:'bd',tipo:'pratica',atividadeId:'',github:'https://github.com/aluno/projeto',email:profile.email,nome:profile.nome,comentario:'',criadoEm:2,notaMax:2};
(async()=>{
 const env=await initializeTestEnvironment({projectId,database:{host:'127.0.0.1',port:9000,rules:readFileSync(resolve(__dirname,'../firebase.rules.json'),'utf8')}});
 let count=0;
 const yes=async task=>{await assertSucceeds(task);count++;},no=async task=>{await assertFails(task);count++;};
 try{
  await env.clearDatabase();
  const guest=env.unauthenticatedContext().database();
  const student=env.authenticatedContext(studentId,{email:profile.email,email_verified:true}).database();
  const other=env.authenticatedContext(otherId,{email:'outro@example.com',email_verified:true}).database();
  const unverified=env.authenticatedContext('unverified_123',{email:profile.email,email_verified:false}).database();
  const teacher=env.authenticatedContext('teacher_123',{email:'brunomichel00@gmail.com',email_verified:true}).database();
  const fakeTeacher=env.authenticatedContext('fake_teacher',{email:'brunomichel00@gmail.com',email_verified:false}).database();
  await no(get(ref(guest,root+'/usuarios/'+studentId)));
  await yes(get(ref(student,root+'/usuarios/'+studentId)));
  await no(get(ref(student,root+'/usuarios')));
  await no(get(ref(other,root+'/usuarios/'+studentId)));
  await no(set(ref(unverified,root+'/usuarios/unverified_123'),profile));
  await yes(set(ref(student,root+'/usuarios/'+studentId),profile));
  await no(update(ref(student,root+'/usuarios/'+studentId),{status:'ativo'}));
  await no(update(ref(student,root+'/usuarios/'+studentId),{role:'admin'}));
  await no(update(ref(student,root+'/usuarios/'+studentId),{materias:{bd:false}}));
  await no(update(ref(student,root+'/usuarios/'+studentId),{criadoEm:999}));
  await yes(get(ref(student,root+'/disciplinas')));
  await no(get(ref(guest,root+'/disciplinas')));
  await no(get(ref(student,root+'/atividades')));
  await no(set(ref(fakeTeacher,root+'/atividades/teste'),{}));
  await yes(set(ref(teacher,root+'/disciplinas/curso_extra'),{nome:'Disciplina nova',instituicao:'UNIVAP',ativo:true}));
  await yes(get(ref(student,root+'/disciplinas/curso_extra')));
  await yes(update(ref(teacher,root+'/usuarios/'+studentId),{status:'ativo'}));
  await yes(get(ref(student,root+'/atividades')));
  await yes(set(ref(student,root+'/submissoes/'+studentId+'/fixed_123'),submission));
  await no(update(ref(student,root+'/submissoes/'+studentId+'/fixed_123'),{comentario:'Substituir'}));
  await no(set(ref(student,root+'/submissoes/'+studentId+'/wrong_course'),{...submission,disciplina:'redes'}));
  await no(set(ref(student,root+'/submissoes/'+studentId+'/wrong_max'),{...submission,notaMax:10}));
  await no(set(ref(student,root+'/submissoes/'+studentId+'/wrong_name'),{...submission,nome:'Outro aluno'}));
  await no(set(ref(student,root+'/submissoes/'+studentId+'/wrong_url'),{...submission,github:'http://github.com/aluno/projeto'}));
  await yes(set(ref(student,root+'/submissoes/'+studentId+'/pages_url'),{...submission,github:'https://aluno.github.io/projeto'}));
  await yes(set(ref(student,root+'/submissoes/'+studentId+'/www_url'),{...submission,github:'https://www.github.com/aluno/projeto'}));
  for(const github of ['https://example.com/aluno/projeto','https://evil.github.com/aluno/projeto','https://github.com/login','https://aluno.github.io/','https://secret@github.com/aluno/projeto','https://github.com:8080/aluno/projeto'])await no(set(ref(student,root+'/submissoes/'+studentId+'/invalid_url'),{...submission,github}));
  const activity={disciplina:'bd',tipo:'projeto',notaMax:7,publicada:true,ativo:true,titulo:'Projeto'};
  await yes(set(ref(teacher,root+'/atividades/activity_123'),activity));
  await yes(set(ref(student,root+'/submissoes/'+studentId+'/custom_123'),{...submission,tipo:'projeto',atividadeId:'activity_123',notaMax:7,atividadeTitulo:'Projeto'}));
  await no(set(ref(student,root+'/submissoes/'+studentId+'/mismatch_type'),{...submission,atividadeId:'activity_123',notaMax:7}));
  await no(set(ref(student,root+'/submissoes/'+studentId+'/mismatch_max'),{...submission,tipo:'projeto',atividadeId:'activity_123',notaMax:10}));
  await yes(update(ref(teacher,root+'/atividades/activity_123'),{publicada:false,ativo:false}));
  await no(set(ref(student,root+'/submissoes/'+studentId+'/archived_123'),{...submission,tipo:'projeto',atividadeId:'activity_123',notaMax:7}));
  await no(set(ref(student,root+'/avaliacoes/'+studentId+'/fixed_123'),{nota:2}));
  await yes(set(ref(teacher,root+'/avaliacoes/'+studentId+'/fixed_123'),{nota:2,comentario:'Ótimo'}));
  await yes(get(ref(student,root+'/avaliacoes/'+studentId)));
  await no(get(ref(other,root+'/avaliacoes/'+studentId)));
  await no(get(ref(student,root+'/iaSugestoes')));
  await no(set(ref(teacher,root+'/iaSugestoes/'+studentId+'/fixed_123'),{}));
  await no(set(ref(student,root+'/iaAnalisesEmCurso/teste'),{}));
  await yes(update(ref(student,root+'/usuarios/'+studentId),{ano:'2º ano',status:'pendente'}));
  await no(get(ref(student,root+'/avaliacoes/'+studentId)));
  await yes(update(ref(teacher,root+'/usuarios/'+studentId),{status:'removido'}));
  await no(update(ref(student,root+'/usuarios/'+studentId),{status:'pendente'}));
  await yes(get(ref(teacher,root+'/usuarios')));
  console.log(`${count} verificações reais de regras passaram no emulador.`);
 }finally{await env.cleanup();}
})().catch(error=>{console.error(error);process.exitCode=1;});
